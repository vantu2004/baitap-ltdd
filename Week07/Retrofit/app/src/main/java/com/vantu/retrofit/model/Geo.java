package com.vantu.retrofit.model;

public class Geo {
    private String lat;
    private String lng;

    // Getter và Setter
    public String getLat() {
        return lat;
    }

    public void setLat(String lat) {
        this.lat = lat;
    }

    public String getLng() {
        return lng;
    }

    public void setLng(String lng) {
        this.lng = lng;
    }
}
